"""Write docs/assets/data.js from the workflow code.

The documentation's column guide, data-flow diagram, output-file list and
command builder read this file, so they always match the code. Run it after
changing columns, resources or output files:

    ./agmp_gwas docs
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

WORKFLOW = Path(__file__).resolve().parent.parent
ROOT = WORKFLOW.parent
sys.path.insert(0, str(WORKFLOW / "scripts"))
from columns import COLUMNS, RECORD_STEPS, RESOURCES  # noqa: E402
from export import ALL_FILES, ALL_SPLITS_HELP, NEW_ONLY  # noqa: E402

import yaml  # noqa: E402


def main():
    if not (ROOT / "docs").is_dir():
        sys.exit("No docs/ folder here: run this from a copy of the AGMP_GWAS repository.")
    cfg = yaml.safe_load((WORKFLOW / "config" / "config.yaml").read_text())
    data = {
        "resources": RESOURCES,
        "columns": COLUMNS,
        "record_steps": RECORD_STEPS,
        "splits": [{"name": k, "desc": v, "new_only": k in NEW_ONLY} for k, v in ALL_SPLITS_HELP.items()],
        "default_csv": ALL_FILES if cfg["export"].get("csv", "all") == "all" else (cfg["export"].get("csv") or []),
        "default_excel": ALL_FILES if cfg["export"].get("excel") == "all" else
                         ([] if cfg["export"].get("excel") in (None, "none") else cfg["export"]["excel"]),
        "qc": cfg["qc"],
        "version": (ROOT / "VERSION").read_text().strip() if (ROOT / "VERSION").exists() else "",
    }
    out = ROOT / "docs" / "assets" / "data.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// Generated by workflow/scripts/docs_data.py. Do not edit by hand.\n"
                   "window.AGMP = " + json.dumps(data, indent=1) + ";\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
